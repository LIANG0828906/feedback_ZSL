"""Deterministic integer-hash weave texture generation."""

from __future__ import annotations

import hashlib
from typing import Any

import numpy as np

_MASK64 = (1 << 64) - 1


def _splitmix64(value: int) -> int:
    value = (value + 0x9E3779B97F4A7C15) & _MASK64
    value = ((value ^ (value >> 30)) * 0xBF58476D1CE4E5B9) & _MASK64
    value = ((value ^ (value >> 27)) * 0x94D049BB133111EB) & _MASK64
    return (value ^ (value >> 31)) & _MASK64


def generate_weave_texture(seed: int, resolution: list[int] | tuple[int, int]) -> np.ndarray:
    """Return an HxW uint8 weave table solely from seed and resolution.

    The table is generated by coordinate hashes and integer triangular waves.
    No process-global RNG, layer traversal state, time, or platform texture is
    involved.  Consequently any layer can be recomputed independently.
    """

    if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
        raise ValueError("seed must be a nonnegative integer")
    if (
        not isinstance(resolution, (list, tuple))
        or len(resolution) != 2
        or not all(isinstance(v, int) and not isinstance(v, bool) and 1 <= v <= 4096 for v in resolution)
    ):
        raise ValueError("resolution must be [width,height] integers in [1,4096]")

    width, height = int(resolution[0]), int(resolution[1])
    warp_period = 7 + int(_splitmix64(seed ^ 0xA24BAED4963EE407) % 7)
    weft_period = 7 + int(_splitmix64(seed ^ 0x9FB21C651E98DF25) % 7)
    warp_phase = int(_splitmix64(seed ^ 0x1D8E4E27C47D124F) % warp_period)
    weft_phase = int(_splitmix64(seed ^ 0xC6BC279692B5CC83) % weft_period)
    diagonal_phase = int(_splitmix64(seed ^ 0xD6E8FEB86659FD93) & 1)

    rows = np.arange(height, dtype=np.int64)[:, None]
    columns = np.arange(width, dtype=np.int64)[None, :]

    warp_position = (columns * 2 + warp_phase) % warp_period
    weft_position = (rows * 2 + weft_phase) % weft_period
    warp_wave = np.abs(warp_position * 2 - (warp_period - 1))
    weft_wave = np.abs(weft_position * 2 - (weft_period - 1))
    warp_profile = 1.0 - warp_wave.astype(np.float64) / max(warp_period - 1, 1)
    weft_profile = 1.0 - weft_wave.astype(np.float64) / max(weft_period - 1, 1)

    cell_x = columns // warp_period
    cell_y = rows // weft_period
    checker = ((cell_x + cell_y + diagonal_phase) & 1).astype(np.float64)
    thread = np.maximum(warp_profile, weft_profile)
    crossing = np.minimum(warp_profile, weft_profile)

    hash_values = (
        (np.uint64(seed & _MASK64))
        ^ (columns.astype(np.uint64) * np.uint64(0xD6E8FEB86659FD93))
        ^ (rows.astype(np.uint64) * np.uint64(0xA24BAED4963EE407))
    )
    # NumPy does not expose splitmix64 as a ufunc; a compact vectorized
    # avalanche with the same constants gives independent deterministic noise.
    hash_values = hash_values ^ (hash_values >> np.uint64(30))
    hash_values = hash_values * np.uint64(0xBF58476D1CE4E5B9)
    hash_values = hash_values ^ (hash_values >> np.uint64(27))
    hash_values = hash_values * np.uint64(0x94D049BB133111EB)
    hash_values = hash_values ^ (hash_values >> np.uint64(31))
    noise = (hash_values & np.uint64(255)).astype(np.float64) / 255.0

    weave = (
        0.25
        + 0.39 * thread
        + 0.14 * checker * (0.35 + 0.65 * thread)
        - 0.09 * crossing
        + 0.12 * noise
    )
    weave = np.clip(weave, 0.0, 1.0)
    return np.rint(weave * 255.0).astype(np.uint8)


def texture_digest(texture: np.ndarray) -> str:
    if texture.dtype != np.uint8 or texture.ndim != 2:
        raise ValueError("texture must be a 2D uint8 array")
    return hashlib.sha256(texture.tobytes(order="C")).hexdigest()


def texture_manifest(layer: dict[str, Any]) -> dict[str, Any]:
    texture = generate_weave_texture(int(layer["weave_seed"]), layer["resolution"])
    return {
        "layer": int(layer["layer"]),
        "id": layer["id"],
        "seed": int(layer["weave_seed"]),
        "resolution": [int(layer["resolution"][0]), int(layer["resolution"][1])],
        "sha256": texture_digest(texture),
    }

