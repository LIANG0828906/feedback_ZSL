SET NOCOUNT ON;

IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = N'{{GATEWAY_LOGIN}}')
BEGIN
    CREATE USER [{{GATEWAY_LOGIN}}] FOR LOGIN [{{GATEWAY_LOGIN}}];
END;

ALTER ROLE db_datareader ADD MEMBER [{{GATEWAY_LOGIN}}];
GRANT SHOWPLAN TO [{{GATEWAY_LOGIN}}];
GRANT VIEW DEFINITION TO [{{GATEWAY_LOGIN}}];
