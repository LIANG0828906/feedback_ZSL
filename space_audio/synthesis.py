"""Deterministic synthesis of the mono dry sources.

No audio assets are shipped. Every dry signal is generated by a fixed
SplitMix64 stream derived from (scene seed, source id, source kind), so the
same scene always yields byte-identical WAV files.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from .rng import DeterministicRng, seed_mix
from .wavio import write_wav


def _time_axis(duration: float, sample_rate: int) -> np.ndarray:
    return np.arange(int(round(duration * sample_rate)), dtype=np.float64) / sample_rate


def synthesize_organ(rng: DeterministicRng, duration: float, sample_rate: int) -> np.ndarray:
    """Sustained organ tone: detuned partials, slow vibrato, amplitude swell."""
    time = _time_axis(duration, sample_rate)
    base = 130.8128  # C3
    partials = [
        (1.0, 0.55),
        (2.0, 0.25),
        (3.0, 0.12),
        (4.0, 0.06),
        (0.5, 0.10),
    ]
    vibrato = 1.0 + 0.0025 * np.sin(2.0 * np.pi * 4.7 * time + 0.3)
    signal = np.zeros_like(time)
    for multiplier, level in partials:
        detune = rng.uniform_range(-0.0015, 0.0015)
        phase = rng.uniform_range(0.0, 2.0 * np.pi)
        signal += level * np.sin(2.0 * np.pi * base * multiplier * vibrato * time + phase)
    noise = rng.noise(time.size) * 0.015
    swell = 0.65 + 0.35 * np.sin(2.0 * np.pi * 0.23 * time)
    attack = 1.0 - np.exp(-time / 0.8)
    release = 1.0 - np.exp(-np.maximum(time[-1] - time, 0.0) / 0.6)
    return (signal + noise) * swell * attack * release


def synthesize_drip(rng: DeterministicRng, duration: float, sample_rate: int) -> np.ndarray:
    """Repeated water-drop pulses: pitched transient plus fast decaying ping."""
    signal = np.zeros_like(_time_axis(duration, sample_rate))
    count = max(1, int(duration / 0.9))
    for index in range(count):
        start = int((0.45 + index * 0.9 + rng.uniform_range(-0.08, 0.08)) * sample_rate)
        length = int(0.18 * sample_rate)
        if start >= signal.size:
            continue
        end = min(signal.size, start + length)
        local_n = end - start
        local_t = np.arange(local_n) / sample_rate
        frequency = 880.0 + rng.uniform_range(-90.0, 90.0)
        envelope = np.exp(-local_t / 0.035)
        ping = np.sin(2.0 * np.pi * frequency * local_t + rng.uniform_range(0.0, 1.0))
        click = rng.noise(local_n) * np.exp(-local_t / 0.004) * 0.6
        signal[start:end] += (ping * envelope + click) * 0.7
    return signal


def synthesize_footstep(rng: DeterministicRng, duration: float, sample_rate: int) -> np.ndarray:
    """Footstep transients: short noise bursts with low-frequency thump."""
    signal = np.zeros_like(_time_axis(duration, sample_rate))
    count = max(1, int(duration / 0.55))
    for index in range(count):
        start = int((0.27 + index * 0.55 + rng.uniform_range(-0.03, 0.03)) * sample_rate)
        length = int(0.12 * sample_rate)
        if start >= signal.size:
            continue
        end = min(signal.size, start + length)
        local_n = end - start
        local_t = np.arange(local_n) / sample_rate
        envelope = np.exp(-local_t / 0.028)
        thump = np.sin(2.0 * np.pi * (110.0 + rng.uniform_range(-12.0, 12.0)) * local_t)
        grit = rng.noise(local_n)
        signal[start:end] += (thump * 0.8 + grit * 0.45) * envelope * 0.8
    return signal


SYNTHESIZERS = {
    "organ": synthesize_organ,
    "drip": synthesize_drip,
    "footstep": synthesize_footstep,
}


def synthesize_dry(kind: str, seed: int, source_id: str, duration: float,
                   sample_rate: int) -> np.ndarray:
    if kind not in SYNTHESIZERS:
        raise ValueError(f"unsupported source kind {kind}")
    rng = DeterministicRng(seed_mix(int(seed), "dry", source_id, kind))
    return SYNTHESIZERS[kind](rng, duration, sample_rate)


def generate_all_dry_sources(scene: dict, base_dir: str | Path) -> dict[str, Path]:
    """Generate every dry WAV declared in the scene and return their paths."""
    base_dir = Path(base_dir)
    sample_rate = int(scene["project"]["sample_rate"])
    duration = float(scene["project"]["duration"])
    seed = int(scene["project"]["seed"])
    written: dict[str, Path] = {}
    for source in scene["sources"]:
        kind = source["kind"]
        signal = synthesize_dry(kind, seed, source["id"], duration, sample_rate)
        target = base_dir / source["file"]
        write_wav(target, signal, sample_rate)
        written[source["id"]] = target
    return written

