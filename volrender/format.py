"""Custom 72-byte header plus raw-voxel volume file format.

The on-disk layout is intentionally small and deterministic so that generated
samples can be hashed and regenerated byte-for-byte.
"""

from __future__ import annotations

import hashlib
import os
import struct
import zlib
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

import numpy as np

from .errors import E_FORMAT, E_IO, VolRenderError


MAGIC = b"VRVOL001"
FORMAT_VERSION = 1
HEADER_SIZE = 72
HEADER_STRUCT = struct.Struct("<8sHHBBBB3I3fffQQII")
FLAG_INTENSITY = 1
FLAG_MASK = 2

DTYPE_TO_CODE: dict[np.dtype, int] = {
    np.dtype(np.uint8): 0,
    np.dtype("<i2"): 1,
    np.dtype("<f4"): 2,
    np.dtype("<u2"): 3,
}
CODE_TO_DTYPE: dict[int, np.dtype] = {
    0: np.dtype(np.uint8),
    1: np.dtype("<i2"),
    2: np.dtype("<f4"),
    3: np.dtype("<u2"),
}


@dataclass(frozen=True)
class VolumeHeader:
    shape: tuple[int, int, int]
    spacing: tuple[float, float, float]
    window_level: float
    window_width: float
    dtype: np.dtype
    flags: int
    payload_bytes: int
    payload_crc32: int
    version: int = FORMAT_VERSION

    @property
    def voxel_count(self) -> int:
        return int(self.shape[0] * self.shape[1] * self.shape[2])

    @property
    def is_mask(self) -> bool:
        return bool(self.flags & FLAG_MASK)

    def as_dict(self) -> dict[str, object]:
        return {
            "version": self.version,
            "shape": list(self.shape),
            "spacing": list(self.spacing),
            "window_level": self.window_level,
            "window_width": self.window_width,
            "dtype": self.dtype.name,
            "flags": self.flags,
            "payload_bytes": self.payload_bytes,
            "payload_crc32": f"{self.payload_crc32:08x}",
        }


@dataclass(frozen=True)
class VolumeFile:
    header: VolumeHeader
    raw: np.ndarray
    path: str
    file_sha256: str


def _header_bytes(header: VolumeHeader, payload_crc32: int) -> bytes:
    if header.shape[0] <= 0 or header.shape[1] <= 0 or header.shape[2] <= 0:
        raise VolRenderError(E_FORMAT, "volume dimensions must be positive")
    if len(header.spacing) != 3 or any(
        not np.isfinite(v) or v <= 0.0 for v in header.spacing
    ):
        raise VolRenderError(E_FORMAT, "voxel spacing must be three positive numbers")
    if not np.isfinite(header.window_width) or header.window_width <= 0.0:
        raise VolRenderError(E_FORMAT, "window width must be positive")
    if not np.isfinite(header.window_level):
        raise VolRenderError(E_FORMAT, "window level must be finite")
    dtype = np.dtype(header.dtype).newbyteorder("<")
    if dtype not in DTYPE_TO_CODE:
        raise VolRenderError(E_FORMAT, f"unsupported scalar type: {dtype}")

    voxel_count = header.voxel_count
    payload_bytes = voxel_count * dtype.itemsize
    prefix = HEADER_STRUCT.pack(
        MAGIC,
        FORMAT_VERSION,
        HEADER_SIZE,
        3,
        DTYPE_TO_CODE[dtype],
        header.flags,
        0,
        *header.shape,
        *header.spacing,
        float(header.window_level),
        float(header.window_width),
        voxel_count,
        payload_bytes,
        payload_crc32,
        0,
    )
    crc = zlib.crc32(prefix) & 0xFFFFFFFF
    return prefix[:-4] + struct.pack("<I", crc)


def write_volume_file(
    path: str | os.PathLike[str],
    raw: np.ndarray,
    *,
    spacing: tuple[float, float, float] = (1.0, 1.0, 1.0),
    window_level: float,
    window_width: float,
    flags: int = FLAG_INTENSITY,
) -> VolumeHeader:
    """Write a volume atomically using the custom header format."""

    arr = np.asarray(raw)
    if arr.ndim != 3:
        raise VolRenderError(E_FORMAT, "volume array must be three-dimensional")
    dtype = arr.dtype.newbyteorder("<")
    if dtype not in DTYPE_TO_CODE:
        raise VolRenderError(E_FORMAT, f"unsupported scalar type: {arr.dtype}")
    arr = np.ascontiguousarray(arr, dtype=dtype)
    payload = arr.tobytes(order="C")
    payload_crc = zlib.crc32(payload) & 0xFFFFFFFF
    shape_xyz = (int(arr.shape[2]), int(arr.shape[1]), int(arr.shape[0]))
    header = VolumeHeader(
        shape=shape_xyz,
        spacing=tuple(float(v) for v in spacing),
        window_level=float(window_level),
        window_width=float(window_width),
        dtype=dtype,
        flags=int(flags),
        payload_bytes=len(payload),
        payload_crc32=payload_crc,
    )
    header_bytes = _header_bytes(header, payload_crc)
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = out_path.with_name(out_path.name + ".tmp")
    try:
        with tmp_path.open("wb") as handle:
            handle.write(header_bytes)
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, out_path)
    except OSError as exc:
        try:
            tmp_path.unlink(missing_ok=True)
        except OSError:
            pass
        raise VolRenderError(E_IO, f"failed to write volume: {out_path}") from exc
    return header


def _read_exact(handle: BinaryIO, size: int, what: str) -> bytes:
    data = handle.read(size)
    if len(data) != size:
        raise VolRenderError(
            E_FORMAT,
            f"truncated volume file while reading {what}",
            details={"expected": size, "actual": len(data)},
        )
    return data


def read_volume_file(path: str | os.PathLike[str]) -> VolumeFile:
    """Parse and validate a custom volume file."""

    file_path = Path(path)
    try:
        file_bytes = file_path.read_bytes()
    except OSError as exc:
        raise VolRenderError(E_IO, f"failed to read volume: {file_path}") from exc

    if len(file_bytes) < HEADER_SIZE:
        raise VolRenderError(E_FORMAT, "volume file is shorter than its header")
    header_bytes = file_bytes[:HEADER_SIZE]
    values = HEADER_STRUCT.unpack(header_bytes)
    (
        magic,
        version,
        header_size,
        ndim,
        dtype_code,
        flags,
        reserved,
        nx,
        ny,
        nz,
        sx,
        sy,
        sz,
        window_level,
        window_width,
        voxel_count,
        payload_bytes,
        payload_crc32,
        header_crc32,
    ) = values

    crc_zeroed = header_bytes[:-4] + b"\x00\x00\x00\x00"
    if (zlib.crc32(crc_zeroed) & 0xFFFFFFFF) != header_crc32:
        raise VolRenderError(E_FORMAT, "volume header CRC mismatch")
    if magic != MAGIC:
        raise VolRenderError(E_FORMAT, "invalid volume magic")
    if version != FORMAT_VERSION:
        raise VolRenderError(
            E_FORMAT,
            "unsupported volume format version",
            details={"expected": FORMAT_VERSION, "actual": version},
        )
    if header_size != HEADER_SIZE or ndim != 3:
        raise VolRenderError(E_FORMAT, "invalid volume header dimensions")
    if dtype_code not in CODE_TO_DTYPE:
        raise VolRenderError(E_FORMAT, f"unknown scalar type code: {dtype_code}")
    dtype = CODE_TO_DTYPE[dtype_code]
    expected_voxels = int(nx) * int(ny) * int(nz)
    expected_bytes = expected_voxels * dtype.itemsize
    if int(voxel_count) != expected_voxels or int(payload_bytes) != expected_bytes:
        raise VolRenderError(E_FORMAT, "volume size fields are inconsistent")
    if len(file_bytes) != HEADER_SIZE + int(payload_bytes):
        raise VolRenderError(
            E_FORMAT,
            "raw payload size does not match the header",
            details={
                "expected": HEADER_SIZE + int(payload_bytes),
                "actual": len(file_bytes),
            },
        )
    payload = file_bytes[HEADER_SIZE:]
    if (zlib.crc32(payload) & 0xFFFFFFFF) != int(payload_crc32):
        raise VolRenderError(E_FORMAT, "volume payload CRC mismatch")
    raw = np.frombuffer(payload, dtype=dtype).reshape((nz, ny, nx)).copy()
    header = VolumeHeader(
        shape=(nx, ny, nz),
        spacing=(sx, sy, sz),
        window_level=window_level,
        window_width=window_width,
        dtype=dtype,
        flags=flags,
        payload_bytes=payload_bytes,
        payload_crc32=payload_crc32,
        version=version,
    )
    file_sha = hashlib.sha256(file_bytes).hexdigest()
    return VolumeFile(header=header, raw=raw, path=str(file_path), file_sha256=file_sha)
