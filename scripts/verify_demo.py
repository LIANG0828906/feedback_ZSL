#!/usr/bin/env python3
"""Run the local acceptance path and write a deterministic report."""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from volrender.config import parse_config
from volrender.errors import AppError
from volrender.incremental import Change, VersionedRenderService
from volrender.injection import INJECTIONS, _read_scene_container, load_inputs
from volrender.pipeline import render_preview, write_preview_outputs
from volrender.render import SimulatedTermination, render_frame, summary_bytes
from volrender.samplegen import write_sample
from volrender.scene import build_scene
from volrender.snapshot import SnapshotCheckpoint, SnapshotStore


ARTIFACT_ROOT = ROOT / "artifacts"
DEMO_ROOT = ARTIFACT_ROOT / "demo"


def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def reset_generated(path: Path) -> None:
    marker = path / ".generated-by-volrender"
    if path.exists():
        if not marker.exists() and any(path.iterdir()):
            raise RuntimeError(
                f"refusing to remove non-generated directory: {path}"
            )
        shutil.rmtree(path)
    path.mkdir(parents=True)
    marker.write_text("generated by scripts/verify_demo.py\n", encoding="ascii")


def mutate_density_scene(scene_path: Path):
    header, payload = _read_scene_container(scene_path.read_bytes())
    values = np.frombuffer(payload, dtype="<f4").copy()
    values[:100] = np.minimum(1.0, values[:100] + 0.2)
    return build_scene(header, values.tobytes())


def main() -> int:
    ARTIFACT_ROOT.mkdir(parents=True, exist_ok=True)
    reset_generated(DEMO_ROOT)
    sample_dir = DEMO_ROOT / "sample"
    scene_path, config_path = write_sample(sample_dir, sample_budget=12000)
    loaded = load_inputs(scene_path, config_path)

    preview = render_preview(
        loaded.scene,
        loaded.config,
        verify_seams=True,
        snapshot_dir=DEMO_ROOT / "preview_snapshots",
    )
    publication = write_preview_outputs(DEMO_ROOT / "preview", preview)
    second = render_preview(
        loaded.scene,
        loaded.config,
        verify_seams=True,
    )
    buffer_equal = {
        precision: preview.renders[precision].color_bytes
        == second.renders[precision].color_bytes
        for precision in preview.renders
    }
    summary_equal = preview.summary_raw == second.summary_raw

    reject_data = json.loads(config_path.read_text(encoding="utf-8"))
    reject_data["sample_budget"] = 100
    rejection: dict[str, Any]
    try:
        render_frame(
            loaded.scene,
            parse_config(reject_data),
            "float64",
        )
        rejection = {"unexpected_success": True}
    except AppError as exc:
        rejection = {
            "code": exc.code.value,
            "rejected_tiles": exc.details["rejected_tiles"],
            "output_written": exc.details["output_written"],
            "wait_queue_events": sum(
                1
                for event in exc.details["trace"]
                if event["event"] == "wait_queue"
            ),
            "complete_events_before_reject": sum(
                1
                for event in exc.details["trace"]
                if event["event"] == "complete"
            ),
        }

    injections: dict[str, Any] = {}
    for injection in INJECTIONS:
        try:
            load_inputs(scene_path, config_path, injection=injection)
            injections[injection] = {"unexpected_success": True}
        except AppError as exc:
            injections[injection] = {
                "code": exc.code.value,
                "field": exc.field,
                "injection_point": exc.injection_point,
            }

    snapshot_store = SnapshotStore(DEMO_ROOT / "recovery" / "snapshots")
    checkpoint = SnapshotCheckpoint(
        snapshot_store,
        loaded.scene,
        loaded.config,
        "float64",
    )
    try:
        render_frame(
            loaded.scene,
            loaded.config,
            "float64",
            checkpoint=checkpoint,
            stop_after=2,
        )
        stop_result = {"unexpected_completion": True}
    except SimulatedTermination as exc:
        stop_result = {"terminated": True, "message": str(exc)}
    latest = snapshot_store.latest_path()
    assert latest is not None
    snapshot = snapshot_store.load_latest(
        loaded.scene, loaded.config, "float64"
    )
    assert snapshot is not None
    resumed = render_frame(
        loaded.scene,
        loaded.config,
        "float64",
        completed=snapshot.completed,
    )
    fresh = preview.renders["float64"]
    skipped = sorted(
        event["tile_index"]
        for event in resumed.trace
        if event["event"] == "resume_skip"
    )
    rendered_after_resume = sorted(
        event["tile_index"]
        for event in resumed.trace
        if event["event"] == "complete"
    )
    recovery = {
        **stop_result,
        "snapshot_file": latest.name,
        "snapshot_files": len(
            list((DEMO_ROOT / "recovery" / "snapshots").glob("*.snapshot.json"))
        ),
        "completed_chunk_indices": sorted(snapshot.completed),
        "chain_head": snapshot.document["chain_head"],
        "resumed_color_equal": resumed.color_bytes == fresh.color_bytes,
        "resumed_summary_equal": (
            summary_bytes(resumed.summary) == summary_bytes(fresh.summary)
        ),
        "resume_skipped_tiles": skipped,
        "rendered_after_resume": rendered_after_resume,
        "duplicate_writes": sorted(set(skipped) & set(rendered_after_resume)),
    }

    changed_scene = mutate_density_scene(scene_path)
    service = VersionedRenderService()
    version_one = service.render_initial(loaded.scene, loaded.config)
    version_two = service.render_change(
        loaded.scene,
        changed_scene,
        loaded.config,
        loaded.config,
        Change("density", block_id=0, reason="smoke block verification"),
    )
    reused_hashes_equal = all(
        version_one.tile_hashes[index]
        == version_two.tile_hashes[index]
        for index in version_two.publication["reused_tiles"]
    )
    incremental = {
        "old_version": version_one.version,
        "new_version": version_two.version,
        "old_buffer_digest": version_one.buffer_digest,
        "new_buffer_digest": version_two.buffer_digest,
        "affected_tiles": version_two.publication["affected_tiles"],
        "reused_tiles": version_two.publication["reused_tiles"],
        "reused_hashes_equal": reused_hashes_equal,
        "conservative": version_two.publication["conservative"],
        "reasons": version_two.publication["reasons"],
        "submitted_tiles": [
            event["tile_index"]
            for event in version_two.artifact.trace
            if event["event"] == "submit"
        ],
    }

    manifest = json.loads(
        (DEMO_ROOT / "preview" / "current" / "manifest.json").read_text(
            encoding="utf-8"
        )
    )
    report = {
        "verification_version": 1,
        "sample": {
            "scene_sha256": sha256_file(scene_path),
            "config_sha256": sha256_file(config_path),
            "scene_fingerprint": loaded.scene.fingerprint,
            "density_version": loaded.scene.density_version,
            "size": [loaded.scene.width, loaded.scene.height],
            "tiles": len(preview.renders["float64"].tiles),
        },
        "render": {
            "version_id": publication["version_id"],
            "degraded_tiles": preview.renders["float64"].summary[
                "degraded_tile_indices"
            ],
            "budget_used": preview.renders["float64"].summary["budget"][
                "used"
            ],
            "tile_stages": [
                {
                    "tile_index": result.tile.index,
                    "stage": result.stage,
                    "step_scale": result.step_scale,
                    "samples_used": result.samples_used,
                    "color_hash": result.color_hash(),
                }
                for result in preview.renders["float64"].tiles
            ],
            "seam": {
                precision: {
                    "ok": check.ok,
                    "max_color_delta": check.max_color_delta,
                    "max_transmittance_delta": (
                        check.max_transmittance_delta
                    ),
                }
                for precision, check in preview.seam_checks.items()
            },
            "determinism": {
                "buffer_equal": buffer_equal,
                "summary_equal": summary_equal,
                "summary_sha256": sha256_bytes(preview.summary_raw),
            },
            "precision_error": preview.precision_error,
            "manifest": manifest,
        },
        "budget_rejection": rejection,
        "injections": injections,
        "recovery": recovery,
        "incremental": incremental,
    }
    report_path = ARTIFACT_ROOT / "verification" / "report.json"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    raw = (
        json.dumps(
            report,
            sort_keys=True,
            indent=2,
            ensure_ascii=False,
            allow_nan=False,
        )
        + "\n"
    ).encode("utf-8")
    temporary = report_path.with_suffix(".tmp")
    temporary.write_bytes(raw)
    temporary.replace(report_path)
    print(
        json.dumps(
            {
                "ok": True,
                "report": str(report_path),
                "preview": str(DEMO_ROOT / "preview" / "current"),
                "degraded_tiles": report["render"]["degraded_tiles"],
                "precision_max_error": preview.precision_error[
                    "max_abs_error"
                ],
                "recovery": {
                    "completed": len(snapshot.completed),
                    "skipped": skipped,
                    "equal": recovery["resumed_color_equal"],
                },
                "incremental": {
                    "affected": incremental["affected_tiles"],
                    "reused": incremental["reused_tiles"],
                    "hashes_equal": reused_hashes_equal,
                },
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
