func fixtureForTest(t *testing.T) *GeneratedFixture {
	t.Helper()
	fixture, err := GenerateFixture(DefaultSeed)
	if err != nil {
		t.Fatal(err)
	}
	return fixture
}

func loadFixtureVersions(t *testing.T, fixture *GeneratedFixture) (*Project, *Project, *Project) {
	t.Helper()
	load := func(raw []byte) *Project {
		project, err := LoadProject(raw)
		if err != nil {
			t.Fatal(err)
		}
		return project
	}
	return load(fixture.V1), load(fixture.V2), load(fixture.V3)
}

func TestThreeSchemasNormalizeIdentically(t *testing.T) {
	fixture := fixtureForTest(t)
	v1, v2, v3 := loadFixtureVersions(t, fixture)
	if v1.SemanticKey() != v2.SemanticKey() || v1.SemanticKey() != v3.SemanticKey() {
		t.Fatalf("semantic keys differ: %s %s %s", v1.SemanticKey(), v2.SemanticKey(), v3.SemanticKey())
	}
}

func TestEngineRunsFixtureAndMatchesTruth(t *testing.T) {
	fixture := fixtureForTest(t)
	_, _, v3 := loadFixtureVersions(t, fixture)
	engine, err := NewEngine(v3)
	if err != nil {
		t.Fatal(err)
	}
	run, err := engine.Run(context.Background(), RunOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if run.Interrupted {
		t.Fatal("unexpected interruption")
	}
	var truth FixtureTruth
	if err := json.Unmarshal(fixture.Truth, &truth); err != nil {
		t.Fatal(err)
	}
	gotBatches := map[int64]BatchResult{}
	for _, tick := range run.Ticks {
		for _, batch := range tick.Batches {
			gotBatches[batch.TimeMS] = batch
		}
	}
	for _, expected := range truth.Batches {
		batch, ok := gotBatches[expected.TimeMS]
		if !ok {
			t.Fatalf("missing batch at %d", expected.TimeMS)
		}
		if stringifyMigrations(batch.Promote) != stringifyStrings(expected.Promote) {
			t.Fatalf("promote at %d: got %v want %v", expected.TimeMS, stringifyMigrations(batch.Promote), expected.Promote)
		}
		if stringifyMigrations(batch.Demote) != stringifyStrings(expected.Demote) {
			t.Fatalf("demote at %d: got %v want %v", expected.TimeMS, stringifyMigrations(batch.Demote), expected.Demote)
		}
	}
	for _, check := range truth.HeatChecks {
		tick := tickAt(run, check.TimeMS)
		if tick == nil {
			t.Fatalf("missing tick %d", check.TimeMS)
		}
		got := objectAt(*tick, check.Object)
		if got == nil || got.HeatLevel != check.Level {
			t.Fatalf("heat at %d %s: got %v want %s", check.TimeMS, check.Object, got, check.Level)
		}
	}
	last := run.Ticks[len(run.Ticks)-1]
	for _, object := range last.Objects {
		if want := truth.FinalLayers[object.ID]; want != "" && object.LayerID != want {
			t.Fatalf("final layer %s: got %s want %s", object.ID, object.LayerID, want)
		}
	}
}

func TestSampleFilesExistAndLoad(t *testing.T) {
	if _, err := os.Stat("samples/v1.json"); errors.Is(err, os.ErrNotExist) {
		t.Skip("samples are generated by cmd/samplegen")
	}
	for _, name := range []string{"samples/v1.json", "samples/v2.json", "samples/v3.json"} {
		raw, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := LoadProject(raw); err != nil {
			t.Fatalf("%s: %v", name, err)
		}
	}
}

func stringifyMigrations(values []Migration) string {
	out := ""
	for i, value := range values {
		if i > 0 {
			out += ","
		}
		out += value.ObjectID
	}
	return out
}

func stringifyStrings(values []string) string {
	out := ""
	for i, value := range values {
		if i > 0 {
			out += ","
		}
		out += value
	}
	return out
}

func tickAt(run *RunResult, at int64) *TickResult {
	for i := range run.Ticks {
		if run.Ticks[i].TimeMS == at {
			return &run.Ticks[i]
		}
	}
	return nil
}

func objectAt(tick TickResult, id string) *ObjectSnapshot {
	for i := range tick.Objects {
		if tick.Objects[i].ID == id {
			return &tick.Objects[i]
		}
	}
	return nil
}
